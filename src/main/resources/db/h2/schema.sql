-- Local/test copy of db/mysql/schema.sql in H2 syntax. Keep both in sync.
DROP TABLE appointments IF EXISTS;
DROP TABLE vet_specialties IF EXISTS;
DROP TABLE visits IF EXISTS;
DROP TABLE pets IF EXISTS;
DROP TABLE vets IF EXISTS;
DROP TABLE hospitals IF EXISTS;
DROP TABLE specialties IF EXISTS;
DROP TABLE types IF EXISTS;
DROP TABLE owners IF EXISTS;

CREATE TABLE hospitals (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_name VARCHAR(255) NOT NULL,
  address       VARCHAR(255) NOT NULL,
  phone         VARCHAR(50)  NOT NULL,
  CONSTRAINT uq_hospitals_phone UNIQUE (phone)
);

CREATE TABLE vets (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id INTEGER      NOT NULL,
  vet_name    VARCHAR(255) NOT NULL,
  FOREIGN KEY (hospital_id) REFERENCES hospitals (id)
);

CREATE TABLE specialties (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  specialty_name VARCHAR(255) NOT NULL
);

CREATE TABLE vet_specialties (
  vet_id       INTEGER NOT NULL,
  specialty_id INTEGER NOT NULL,
  FOREIGN KEY (vet_id) REFERENCES vets (id),
  FOREIGN KEY (specialty_id) REFERENCES specialties (id),
  CONSTRAINT uq_vet_specialties UNIQUE (vet_id, specialty_id)
);

-- VARCHAR_IGNORECASE mirrors the case-insensitive utf8mb4_unicode_ci collation of MySQL
CREATE TABLE owners (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_name VARCHAR_IGNORECASE(255) NOT NULL,
  address    VARCHAR(255)            NOT NULL,
  phone      VARCHAR(50)             NOT NULL,
  CONSTRAINT uq_owners_phone UNIQUE (phone)
);

CREATE TABLE types (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_name VARCHAR(255) NOT NULL
);

CREATE TABLE pets (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_id    INTEGER                 NOT NULL,
  owner_id   INTEGER                 NOT NULL,
  pet_name   VARCHAR_IGNORECASE(255) NOT NULL,
  birth_date DATE                    NOT NULL,
  FOREIGN KEY (type_id) REFERENCES types (id),
  FOREIGN KEY (owner_id) REFERENCES owners (id)
);

CREATE TABLE visits (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id      INTEGER      NOT NULL,
  visit_date  DATE         NOT NULL,
  description VARCHAR(255) NOT NULL,
  prescription VARCHAR(255),
  FOREIGN KEY (pet_id) REFERENCES pets (id)
);

CREATE TABLE appointments (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id    INTEGER      NOT NULL,
  pet_id         INTEGER      NOT NULL,
  vet_id         INTEGER      NOT NULL,
  appointment_at TIMESTAMP    NOT NULL,
  status         VARCHAR(20)  NOT NULL DEFAULT 'REQUESTED',
  reason         VARCHAR(255),
  created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  -- same rule as MySQL: 1 while the slot is held, NULL once cancelled
  active_slot    INTEGER GENERATED ALWAYS AS (CASE WHEN status = 'CANCELLED' THEN NULL ELSE 1 END),
  UNIQUE (vet_id, appointment_at, active_slot),
  UNIQUE (pet_id, appointment_at, active_slot),
  FOREIGN KEY (hospital_id) REFERENCES hospitals (id),
  FOREIGN KEY (pet_id) REFERENCES pets (id),
  FOREIGN KEY (vet_id) REFERENCES vets (id),
  CONSTRAINT chk_appointment_status CHECK (status IN ('REQUESTED', 'CONFIRMED', 'CANCELLED', 'COMPLETED'))
);
CREATE INDEX idx_appointments_hospital_time ON appointments (hospital_id, appointment_at);
CREATE INDEX idx_appointments_vet_time ON appointments (vet_id, appointment_at);
CREATE INDEX idx_appointments_pet_time ON appointments (pet_id, appointment_at);
